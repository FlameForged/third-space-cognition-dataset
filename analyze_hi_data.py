"""
Basic analysis script for HI_Data.csv.

This script loads the exploratory human-AI interaction dataset and generates
simple descriptive summaries for the coded observations.

Dataset: HI_Data.csv
Related research: Third-Space Cognition: A Theory-Driven Review
of Sustained Human-AI Coupling
DOI: 10.5281/zenodo.18679265
"""

from pathlib import Path
import pandas as pd


DATA_FILE = Path("HI_Data.csv")
OUTPUT_FILE = Path("analysis_summary.md")


def safe_value_counts(df: pd.DataFrame, column: str) -> str:
    """Return value counts for a column if it exists."""
    if column not in df.columns:
        return f"## {column}\n\nColumn not found in dataset.\n"

    counts = df[column].fillna("Not specified").value_counts()

    lines = [f"## {column}", ""]
    for value, count in counts.items():
        lines.append(f"- {value}: {count}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    if not DATA_FILE.exists():
        raise FileNotFoundError(
            f"Could not find {DATA_FILE}. Make sure HI_Data.csv is in the same folder."
        )

    df = pd.read_csv(DATA_FILE)

    report = [
        "# HI Dataset Analysis Summary",
        "",
        "This file was generated by `analyze_hi_data.py`.",
        "",
        "## Dataset Overview",
        "",
        f"- Total observations: {len(df)}",
        f"- Total fields: {len(df.columns)}",
        "- Review manuscript snapshot: 27 observations (session IDs 001–027)",
        "- Repository status: evolving dataset; later additions are not analyzed in the submitted review",
        "",
        "## Columns",
        "",
    ]

    for column in df.columns:
        report.append(f"- {column}")

    report.append("")

    columns_to_summarize = [
        "model",
"platform",
"session_type",
"primary_pattern",
"secondary_pattern",
"user_prompt_type",
"model_response_type",
"safety_intervention_present",
"memory_available",
"evidence_strength",
"coding_confidence",

    ]

    for column in columns_to_summarize:
        report.append(safe_value_counts(df, column))

    OUTPUT_FILE.write_text("\n".join(report), encoding="utf-8")

    print(f"Loaded {len(df)} observations from {DATA_FILE}.")
    print(f"Analysis summary written to {OUTPUT_FILE}.")


if __name__ == "__main__":
    main()
